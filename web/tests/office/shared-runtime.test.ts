import { test } from "node:test";
import assert from "node:assert/strict";
import { createSharedOfficeRuntime as create, reduceSharedOffice as reduce, sessionActorId } from "../../src/office/sharedRuntime";
import { deriveSharedOfficeModel as model } from "../../src/office/model";
import { sharedWorkerPath, pathDuration } from "../../src/office/routes";
import { OFFICE_LAYOUT as layout } from "../../src/office/layout";
import { populated, snapshot, session, delegation } from "./fixtures";

test("global capacity includes coordinators, preserves seats and reveals overflow without events", () => {
  const snap = populated(11), m = model(snap), r = create(m, true, 0);
  assert.equal(r.workers.length, 10);
  assert.equal(r.model.sessionIds.length, 12);
  assert.ok(r.workers.some(w => w.sessionId === "main"));
  const next = reduce(r, { type: "snapshot", model: model({ ...snap, sessions: snap.sessions.toReversed() }), nowMs: 10 });
  assert.deepEqual(next.workers, r.workers);
  const id = m.sessionIds.find(id => !r.workers.some(w => w.sessionId === id))!;
  const selected = reduce(r, { type: "select", selection: { kind: "session", sessionId: "main" } });
  const revealed = reduce(selected, { type: "revealWorker", sessionId: id, nowMs: 20 });
  assert.equal(revealed.workers.length, 10);
  assert.ok(revealed.workers.some(w => w.sessionId === id));
  assert.ok(revealed.workers.some(w => w.sessionId === "main"));
  assert.deepEqual(revealed.queue, []);
  const transient = { ...r, workers: r.workers.map(w => ({ ...w, phase: "entering" as const })) };
  assert.ok(reduce(transient, { type: "revealWorker", sessionId: id, nowMs: 30 }).workers.some(w => w.sessionId === id));
});
test("admission prioritizes attention then work then stable IDs, without shuffling occupied seats", () => {
  const snap = snapshot([session("z", "coder", "needs_human"), session("a", "coder", "blocked"), session("c"), session("b")]);
  const r = create(model(snap), true, 0);
  assert.deepEqual(r.workers.map(w => w.sessionId), ["z", "b", "c", "a"]);
  snap.sessions[1].state = "needs_human";
  assert.deepEqual(reduce(r, { type: "snapshot", model: model(snap), nowMs: 1 }).workers, r.workers);
});
test("tick frees departure slots and fills overflow without another snapshot", () => {
  const snap = populated(11);
  let r = create(model(snap), true, 0);
  const departed = r.workers.find(w => w.sessionId !== "main")!.sessionId;
  snap.sessions.find(s => s.sessionId === departed)!.state = "done";
  r = reduce(r, { type: "snapshot", model: model(snap), nowMs: 10 });
  assert.equal(r.workers.length, 10);
  r = reduce(r, { type: "tick", nowMs: 1510 });
  r = reduce(r, { type: "tick", nowMs: 100000 });
  assert.equal(r.workers.length, 10);
  assert.ok(!r.workers.some(w => w.sessionId === departed));
  assert.equal(r.model.sessionsById.get(departed)!.state, "done");
});
test("quiet reconnect, interrupted entry, resumption, and disappearance retain truthful lifecycle", () => {
  let r = create(model(snapshot()), true, 0);
  const snap = populated(1);
  r = reduce(r, { type: "snapshot", model: model(snap), nowMs: 10 });
  assert.equal(r.workers.filter(w => w.phase === "entering").length, 2);
  snap.sessions[1].state = "blocked";
  r = reduce(r, { type: "snapshot", model: model(snap), nowMs: 20 });
  assert.equal(r.workers.find(w => w.sessionId === "worker-0")!.phase, "seated");
  snap.sessions[1].state = "done";
  r = reduce(r, { type: "snapshot", model: model(snap), nowMs: 30 });
  assert.equal(r.workers.find(w => w.sessionId === "worker-0")!.phase, "reporting");
  snap.sessions[1].state = "working";
  r = reduce(r, { type: "snapshot", model: model(snap), nowMs: 40 });
  assert.equal(r.workers.find(w => w.sessionId === "worker-0")!.phase, "seated");
  const camera = { position: [1, 2, 3] as const, target: [0, 0, 0] as const, zoom: 10 };
  r = reduce(r, { type: "camera", pose: camera });
  r = reduce(r, { type: "connectivity", online: false, nowMs: 50 });
  r = reduce(r, { type: "snapshot", model: model(populated(3)), nowMs: 60 });
  r = reduce(r, { type: "connectivity", online: true, nowMs: 70 });
  assert.deepEqual(r.queue, []);
  assert.ok(r.workers.every(w => w.phase === "seated"));
  assert.deepEqual(r.camera, camera);
  const removed = model(snapshot([session("main", "coordinator")]));
  r = reduce(r, { type: "snapshot", model: removed, nowMs: 80 });
  assert.ok(!r.queue.some(e => e.kind === "report"));
});
test("bursts cap the shared queue and transition crowd; completed and absent reveals create no bodies", () => {
  let r = create(model(snapshot()), true, 0);
  const snap = populated(20);
  r = reduce(r, { type: "snapshot", model: model(snap), nowMs: 10 });
  assert.equal(r.workers.length, 10);
  assert.ok(r.queue.length <= 12);
  assert.ok(r.queue.filter(e => e.startedAt !== undefined).length <= 2);
  assert.equal(r.workers.filter(w => w.phase !== "seated").length, 2);
  assert.deepEqual(reduce(r, { type: "revealWorker", sessionId: "missing", nowMs: 20 }).workers, r.workers);
  for (const s of snap.sessions) s.state = "done";
  r = reduce(r, { type: "snapshot", model: model(snap), nowMs: 30 });
  assert.ok(r.workers.filter(w => w.phase !== "seated").length <= 2);
  const count = r.workers.length;
  assert.equal(reduce(r, { type: "revealWorker", sessionId: "worker-19", nowMs: 40 }).workers.length, count);
});
test("exact session anchors and departure paths never use a representative for an absent parent", () => {
  assert.notEqual(sessionActorId("assistant"), "assistant");
  assert.notEqual(sessionActorId("human"), "human");
  const snap = snapshot([session("a"), session("b"), session("w")], [delegation("bw", "b", "w"), delegation("aw", "a", "w")]);
  const m = model(snap), r = create(m, true, 0);
  const w = { ...r.workers.find(w => w.sessionId === "w")!, phase: "leaving" as const };
  const a = layout.seats.find(s => s.id === r.workers.find(w => w.sessionId === "a")!.seatId)!;
  const path = sharedWorkerPath(layout, w, m, r.workers);
  assert.ok(path.some(p => p.join() === a.approach.join()));
  assert.deepEqual(path.at(-1), layout.entry);
  assert.ok(pathDuration(path) > 0);
  const direct = sharedWorkerPath(layout, w, m, [w]);
  assert.ok(!direct.some(p => p.join() === layout.leads.coordinator.join()));
});
